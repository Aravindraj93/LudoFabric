"""Change requests on finished LudoFabric games and on external Unity projects. No Unity or paid calls."""
import json
from pathlib import Path
from tempfile import TemporaryDirectory
import unittest
from unittest.mock import Mock, patch

from gameagent.change import ChangePlan, ChangeRunner, environment_for, profile_project, rollback
from gameagent.config import Config
from gameagent.orchestrator import Orchestrator
from gameagent.schemas import AgentOutput, FilePatch, FileWrite, TaskSpec
from gameagent.unity.runner import UnityResult

PLAYER = "namespace MyGame {\n  public class Player {\n    public float speed = 5f;\n  }\n}\n"


def make_unity_project(root: Path, rp_package=None, input_handler="0") -> Path:
    (root / "Assets/Scripts").mkdir(parents=True)
    (root / "ProjectSettings").mkdir()
    (root / "Packages").mkdir()
    (root / "Assets/Scripts/Player.cs").write_text(PLAYER, encoding="utf-8")
    (root / "Assets/Main.unity").write_text("%YAML", encoding="utf-8")
    (root / "ProjectSettings/ProjectVersion.txt").write_text("m_EditorVersion: 2022.3.40f1\n")
    (root / "ProjectSettings/ProjectSettings.asset").write_text(f"  activeInputHandler: {input_handler}\n")
    (root / "ProjectSettings/EditorBuildSettings.asset").write_text("    path: Assets/Main.unity\n")
    deps = {"com.unity.ugui": "1.0.0", "com.unity.modules.audio": "1.0.0"}
    if rp_package:
        deps[rp_package] = "14.0.0"
    (root / "Packages/manifest.json").write_text(json.dumps({"dependencies": deps}))
    return root


def plan(**kw):
    return ChangePlan(summary="Add double jump", acceptance=["Press Space twice"], tasks=[
        TaskSpec(id="jump", role="gameplay", title="Double jump", description="Add jumps",
                 outputs=["Assets/Scripts/Player.cs"]),
        TaskSpec(id="fx", role="vfx", title="Dust", description="Dust effect", depends_on=["jump"],
                 outputs=["Assets/Scripts/JumpDust.cs"])], **kw)


OUTPUTS = {
    "jump": AgentOutput(patches=[FilePatch(path="Assets/Scripts/Player.cs", old="public float speed = 5f;",
                                           new="public float speed = 5f;\n    public int maxJumps = 2;")]),
    "fx": AgentOutput(files=[FileWrite(path="Assets/Scripts/JumpDust.cs", content="namespace MyGame { class JumpDust {} }")]),
}


class ChangeTests(unittest.TestCase):
    def setUp(self):
        self.tmp = TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)

    def orch(self, path, unity=False):
        cfg = Config()
        cfg.unity_editor = str(self.root / "Unity.exe") if unity else ""
        if unity:
            (self.root / "Unity.exe").write_text("")
        o = Orchestrator(cfg, path)
        o.llm.structured = Mock(return_value=plan())
        o.studio.execute = Mock(side_effect=lambda role, brief, task, *a: OUTPUTS[task.id])
        return o

    def test_profile_detects_builtin_legacy_project(self):
        p = profile_project(make_unity_project(self.root / "Ext"))
        self.assertEqual((p["unity_version"], p["render_pipeline"], p["input"]), ("2022.3.40f1", "builtin", "legacy"))
        self.assertEqual(p["build_scenes"], ["Assets/Main.unity"])
        self.assertIn("MyGame", p["namespaces"])
        env = environment_for(p)
        self.assertIn('"Standard"', env)
        self.assertIn("legacy UnityEngine.Input", env)
        self.assertIn("NOT generated by LudoFabric", env)
        hd = profile_project(make_unity_project(self.root / "Hd", "com.unity.render-pipelines.high-definition", "1"))
        self.assertEqual((hd["render_pipeline"], hd["input"]), ("hdrp", "input_system"))

    def test_external_project_change_applied_backed_up_and_rolled_back(self):
        path = make_unity_project(self.root / "My Game")
        o = self.orch(path)
        rec = ChangeRunner(o).run("Add a double jump with dust")
        self.assertEqual(rec["status"], "applied_unverified")  # honest: no Unity configured
        self.assertIn("maxJumps", (path / "Assets/Scripts/Player.cs").read_text())
        self.assertTrue((path / "Assets/Scripts/JumpDust.cs").exists())
        self.assertFalse((path / "Assets/GameAgentBridge").exists())  # external project untouched by bridge
        self.assertIn("NOT generated by LudoFabric", o.studio.env_override)
        prompt = o.llm.structured.call_args.kwargs["prompt"]
        self.assertIn("Assets/Scripts/Player.cs", prompt)              # retrieval + file list, not full sources
        self.assertNotIn("public float speed", prompt)
        rollback(o, rec["id"])
        self.assertEqual((path / "Assets/Scripts/Player.cs").read_text(encoding="utf-8"), PLAYER)
        self.assertFalse((path / "Assets/Scripts/JumpDust.cs").exists())

    def test_external_compile_error_repaired_with_plain_compile(self):
        path = make_unity_project(self.root / "Ext")
        o = self.orch(path, unity=True)
        bad = UnityResult(1, "", [{"file": "Assets/Scripts/JumpDust.cs", "line": "1", "col": "1",
                                   "code": "CS0246", "msg": "The type 'Foo' could not be found"}])
        o.project.runner.run = Mock(side_effect=[bad, UnityResult(0, "")])
        o.studio.fix = Mock(return_value=AgentOutput(files=[FileWrite(path="Assets/Scripts/JumpDust.cs", content="// ok")]))
        rec = ChangeRunner(o).run("Add a double jump")
        self.assertEqual(rec["status"], "verified")
        self.assertTrue(rec["verification"]["compiled"])
        self.assertIsNone(o.project.runner.run.call_args_list[0].kwargs.get("method"))  # no bridge method
        o.studio.fix.assert_called_once()

    def test_finished_ludofabric_game_can_be_upgraded(self):
        path = make_unity_project(self.root / "Coin")
        (path / "Assets/GameAgentBridge").mkdir()
        o = self.orch(path, unity=True)
        o.state.phase = "built"
        o.project.compile = Mock(return_value=UnityResult(0, ""))
        o.project.run_tests = Mock(return_value=(True, "3 tests passed"))
        rec = ChangeRunner(o).run("Add a double jump")
        self.assertEqual(rec["status"], "verified")
        self.assertIsNone(o.studio.env_override)  # own projects keep the LudoFabric URP environment
        self.assertTrue(rec["verification"]["tests_EditMode"])

    def test_unfinished_ludofabric_game_is_not_changed(self):
        path = make_unity_project(self.root / "Coin")
        (path / "Assets/GameAgentBridge").mkdir()
        o = self.orch(path)
        o.state.phase = "planned"
        with self.assertRaises(SystemExit):
            ChangeRunner(o).run("x")

    def test_interrupted_change_resumes_without_repeating_paid_calls(self):
        path = make_unity_project(self.root / "Ext")
        o = self.orch(path)
        calls = []
        def flaky(role, brief, task, *a):
            calls.append(task.id)
            if task.id == "fx" and calls.count("fx") == 1:
                raise RuntimeError("transport closed")
            return OUTPUTS[task.id]
        o.studio.execute = Mock(side_effect=flaky)
        with self.assertRaises(RuntimeError):
            ChangeRunner(o).run("Add a double jump")
        self.assertEqual(o.state.changes[0]["status"], "failed")
        restarted = self.orch(path)
        restarted.studio.execute = Mock(side_effect=flaky)
        calls_before = len(calls)
        rec = ChangeRunner(restarted).run("Add a double jump")
        self.assertEqual(rec["status"], "applied_unverified")
        restarted.llm.structured.assert_not_called()          # plan reused from disk
        self.assertEqual(calls[calls_before:], ["fx"])        # finished task replayed from its journal
        self.assertEqual(len(restarted.state.changes), 1)
        self.assertEqual((path / "Assets/Scripts/Player.cs").read_text().count("maxJumps"), 1)

    def test_dashboard_opens_external_project_without_checkpoint(self):
        from webapp import server
        path = make_unity_project(self.root / "Some Game")
        with patch.object(server, "STUDIO_DIR", self.root / "studio"), \
             patch.object(server, "projects_root", return_value=self.root / "default"), \
             patch.object(server.runner, "busy", return_value=False):
            result = server.import_project(server.ImportProject(path=str(path)))
            self.assertEqual(result["project"], "Some_Game")
            state = server.project("Some_Game")["state"]
            self.assertEqual(state["origin"], "external")
            self.assertEqual(state["profile"]["render_pipeline"], "builtin")
            self.assertEqual([p["name"] for p in server.list_projects()], ["Some_Game"])
        with self.assertRaises(server.HTTPException):
            server.import_project(server.ImportProject(path=str(self.root / "default")))


if __name__ == "__main__":
    unittest.main()
