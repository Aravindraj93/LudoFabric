"""Persistent, resumable pipeline state (stored in <project>.agent/state.json)."""
from __future__ import annotations

import json
import os
import tempfile
import time
from pathlib import Path

from pydantic import BaseModel, Field

from .schemas import GameDesign, Plan


def atomic_json(path: Path, value: dict) -> None:
    """Keep the previous checkpoint intact if a process stops during a write."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=path.name, suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            json.dump(value, stream, indent=2, ensure_ascii=False)
            stream.flush()
            os.fsync(stream.fileno())
        for attempt in range(7):
            try:
                os.replace(tmp, path)
                break
            except PermissionError as exc:
                if attempt == 6:
                    # Do not truncate a valid checkpoint or discard the new one on a persistent lock.
                    recovery = tmp
                    tmp = None
                    raise PermissionError(
                        f"Cannot replace checkpoint {path}. Close programs holding this file and check folder "
                        f"permissions. Previous checkpoint is intact; new data preserved at {recovery}."
                    ) from exc
                time.sleep(min(0.05 * 2 ** attempt, 0.8))
    finally:
        if tmp:
            Path(tmp).unlink(missing_ok=True)


class State(BaseModel):
    revision_source: str = ""
    workflow: dict = Field(default_factory=dict)  # durable graph execution identity, separate from game content
    request: str = ""
    design: GameDesign | None = None
    plan: Plan | None = None
    phase: str = "new"  # new -> designed -> planned -> project -> assets -> built -> polished -> shipped
    builder_methods: list[str] = Field(default_factory=list)
    polish_round: int = 0
    reviews: list[dict] = Field(default_factory=list)
    log: list[str] = Field(default_factory=list)
    # Schema version lets later releases migrate checkpoints instead of rejecting them.
    schema_version: int = 2
    # Verified results only (compile/tests/build/smoke/visual gate). Drives the maturity level.
    evidence: dict = Field(default_factory=dict)
    maturity: dict = Field(default_factory=dict)
    # "ludofabric" = generated by this tool; "external" = an existing Unity project opened by path.
    origin: str = "ludofabric"
    profile: dict = Field(default_factory=dict)      # detected engine/pipeline/packages (external projects)
    changes: list[dict] = Field(default_factory=list)  # post-completion change requests and their verification
    targets: list[str] = Field(default_factory=lambda: ["windows"])  # user-chosen build platforms

    @classmethod
    def load(cls, path: Path) -> "State":
        if path.exists():
            return cls.model_validate(json.loads(path.read_text(encoding="utf-8")))
        return cls()

    def save(self, path: Path) -> None:
        atomic_json(path, self.model_dump(mode="json"))

    def add_builders(self, methods: list[str]) -> None:
        for m in methods:
            m = m.strip()
            if m and m not in self.builder_methods:
                self.builder_methods.append(m)

